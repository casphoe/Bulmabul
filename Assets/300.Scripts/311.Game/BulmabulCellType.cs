/// <summary>
/// 부루마불 보드 칸 타입.
/// 칸 타입에 따라 도착했을 때 실행되는 효과가 달라진다.
/// </summary>
public enum BulmabulCellType
{
    /// <summary>
    /// 시작 지점.
    /// 통과하거나 도착하면 월급/보너스를 받는다.
    /// </summary>
    Start = 0,

    /// <summary>
    /// 구매 가능한 일반 땅.
    /// 주인이 없으면 구매 가능, 주인이 있으면 통행료를 지불한다.
    /// </summary>
    Land = 1,

    /// <summary>
    /// 세금 칸.
    /// 도착하면 일정 재화를 차감한다.
    /// </summary>
    Tax = 2,

    /// <summary>
    /// 보너스 칸.
    /// 도착하면 일정 재화를 획득한다.
    /// </summary>
    Bonus = 3,

    /// <summary>
    /// 찬스 카드 칸.
    /// 추후 카드 시스템을 붙일 수 있도록 분리해둔 타입.
    /// </summary>
    Chance = 4,

    /// <summary>
    /// 무인도/감옥/휴식 칸.
    /// 현재 코드는 로그만 남긴다.
    /// 추후 몇 턴 쉬기 기능을 붙일 수 있다.
    /// </summary>
    Jail = 5,

    /// <summary>
    /// 기차 여행 / 우주 여행 같은 특수 이동 칸.
    /// 도착 즉시 이동하는 것이 아니라,
    /// 다음 자기 턴에 일정 비용을 내고 원하는 칸으로 이동할 수 있다.
    /// </summary>
    Travel = 6,
}